/// Wire-protocol constants the web client shares with the engine (capability
/// strings gate feature degradation; chunk sizes bound transfer loops).
fn constants_ts() -> String {
    use roboco_proto::capabilities;
    let mut out = String::new();
    out.push_str(HEADER);
    out.push_str("\n\n");
    out.push_str(
        "/** Protocol feature strings advertised in `EngineInfo.capabilities` / `Device.capabilities`. */\n",
    );
    out.push_str(&format!(
        "export const MESSAGE_QUEUE_V1 = {:?};\n",
        capabilities::MESSAGE_QUEUE_V1
    ));
    out.push_str(&format!(
        "export const MESSAGE_QUEUE_ACTIONS_V1 = {:?};\n",
        capabilities::MESSAGE_QUEUE_ACTIONS_V1
    ));
    out.push_str(&format!(
        "export const MESSAGE_QUEUE_ATTACHMENTS_V1 = {:?};\n",
        capabilities::MESSAGE_QUEUE_ATTACHMENTS_V1
    ));
    out.push_str(&format!(
        "export const MESSAGE_QUEUE_CLEAN_ATTACHMENT_TEXT_V1 = {:?};\n",
        capabilities::MESSAGE_QUEUE_CLEAN_ATTACHMENT_TEXT_V1
    ));
    out.push_str(&format!(
        "export const MESSAGE_QUEUE_EDIT_LEASE_V1 = {:?};\n",
        capabilities::MESSAGE_QUEUE_EDIT_LEASE_V1
    ));
    out.push_str("\n/** Every capability this build of the engine advertises. */\n");
    let current: Vec<String> = capabilities::CURRENT
        .iter()
        .map(|c| format!("{c:?}"))
        .collect();
    out.push_str(&format!(
        "export const CAPABILITIES_CURRENT: readonly string[] = [{}];\n",
        current.join(", ")
    ));
    out.push_str(&format!(
        "\nexport const PREVIEW_PROXY_PORT = {};\n",
        roboco_proto::PREVIEW_PROXY_PORT
    ));
    out.push_str(&format!(
        "export const MAX_WORKSPACE_IMAGE_BYTES = {};\n",
        roboco_proto::MAX_WORKSPACE_IMAGE_BYTES
    ));
    out.push_str(&format!(
        "export const WORKSPACE_IMAGE_CHUNK_BYTES = {};\n",
        roboco_proto::WORKSPACE_IMAGE_CHUNK_BYTES
    ));
    out.push_str(&format!(
        "\n/** Session-scoped id of the live plan/todo chip (ACP plan updates carry no wire id). */\n\
         export const LIVE_PLAN_TOOL_ID = {:?};\n",
        roboco_proto::LIVE_PLAN_TOOL_ID
    ));
    let model_keys: Vec<String> = roboco_proto::SUBAGENT_MODEL_KEYS
        .iter()
        .map(|c| format!("{c:?}"))
        .collect();
    out.push_str(&format!(
        "\n/** Spawn-input keys that carry a child model, in precedence order. */\n\
         export const SUBAGENT_MODEL_KEYS: readonly string[] = [{}];\n",
        model_keys.join(", ")
    ));
    let input_keep: Vec<String> = roboco_proto::SUBAGENT_INPUT_KEEP
        .iter()
        .map(|c| format!("{c:?}"))
        .collect();
    out.push_str(&format!(
        "\n/** The only spawn-input keys preserved in a doc-side tool call. */\n\
         export const SUBAGENT_INPUT_KEEP: readonly string[] = [{}];\n",
        input_keep.join(", ")
    ));
    out
}

/// Replace the ts-rs header with ours and annotate legacy wire names.
fn postprocess(dir: &Path) -> Result<BTreeMap<String, String>> {
    let mut files = BTreeMap::new();
    for entry in fs::read_dir(dir).with_context(|| format!("read {}", dir.display()))? {
        let entry = entry?;
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) != Some("ts") {
            continue;
        }
        let stem = path
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or_default()
            .to_string();
        let content =
            fs::read_to_string(&path).with_context(|| format!("read {}", path.display()))?;
        let body = content
            .strip_prefix(TS_RS_HEADER)
            .map(|rest| rest.trim_start_matches(['\r', '\n']))
            .unwrap_or(&content);
        let mut out = String::from(HEADER);
        out.push('\n');
        if let Some(note) = LEGACY_NOTES
            .iter()
            .find(|(name, _)| *name == stem)
            .map(|(_, note)| *note)
        {
            out.push_str("// ");
            out.push_str(note);
            out.push('\n');
        }
        out.push('\n');
        out.push_str(body);
        files.insert(stem, out);
    }
    Ok(files)
}

fn generate(dir: &Path) -> Result<()> {
    if dir.exists() {
        fs::remove_dir_all(dir).with_context(|| format!("clean {}", dir.display()))?;
    }
    fs::create_dir_all(dir).with_context(|| format!("create {}", dir.display()))?;

    // JSON numbers, not bigints: no wire field exceeds 2^53 (epoch millis,
    // byte counts). Extensionless imports match the workspace's bundler
    // module resolution.
    let cfg = Config::new()
        .with_out_dir(dir)
        .with_large_int("number")
        .with_import_extension(None::<String>);
    export_all(&cfg)?;

    let mut files = postprocess(dir)?;
    files.insert("constants".to_string(), constants_ts());

    let mut index = String::from(HEADER);
    index.push_str("\n\n");
    for name in files.keys() {
        index.push_str(&format!("export * from \"./{name}\";\n"));
    }
    files.insert("index".to_string(), index);

    for (stem, content) in &files {
        fs::write(dir.join(format!("{stem}.ts")), content)
            .with_context(|| format!("write {stem}.ts"))?;
    }
    Ok(())
}

/// Snapshot a directory of generated files as `relpath -> bytes`.
fn snapshot(dir: &Path) -> Result<BTreeMap<String, Vec<u8>>> {
    let mut files = BTreeMap::new();
    if !dir.exists() {
        return Ok(files);
    }
    for entry in fs::read_dir(dir).with_context(|| format!("read {}", dir.display()))? {
        let path = entry?.path();
        if path.is_file() {
            let name = path
                .file_name()
                .and_then(|n| n.to_str())
                .unwrap_or_default()
                .to_string();
            files.insert(name, fs::read(&path)?);
        }
    }
    Ok(files)
}

fn check(real: &Path) -> Result<bool> {
    let tmp = tempfile::tempdir().context("create temp dir")?;
    let fresh = tmp.path().join("generated");
    generate(&fresh)?;

    let expected = snapshot(&fresh)?;
    let actual = snapshot(real)?;
    let mut stale: Vec<String> = Vec::new();
    for (name, bytes) in &expected {
        match actual.get(name) {
            None => stale.push(format!("{name}: missing (not generated)")),
            Some(actual) if actual != bytes => stale.push(format!("{name}: differs")),
            Some(_) => {}
        }
    }
    for name in actual.keys() {
        if !expected.contains_key(name) {
            stale.push(format!("{name}: leftover (no longer generated)"));
        }
    }
    if stale.is_empty() {
        return Ok(true);
    }
    eprintln!(
        "wire types are stale — regenerate with `cargo run -p wiregen`:\n  {}",
        stale.join("\n  ")
    );
    Ok(false)
}

fn main() -> ExitCode {
    let check_mode = std::env::args().any(|arg| arg == "--check");
    let unknown: Vec<String> = std::env::args()
        .skip(1)
        .filter(|arg| arg != "--check")
        .collect();
    if !unknown.is_empty() {
        eprintln!("usage: wiregen [--check]");
        return ExitCode::FAILURE;
    }

    let out_dir =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../web/packages/proto/src/generated");
    if check_mode {
        return match check(&out_dir) {
            Ok(true) => {
                println!("wire types are fresh ({}).", out_dir.display());
                ExitCode::SUCCESS
            }
            Ok(false) => ExitCode::FAILURE,
            Err(err) => {
                eprintln!("wiregen: {err:#}");
                ExitCode::FAILURE
            }
        };
    }
    match generate(&out_dir) {
        Ok(()) => {
            println!("generated {}", out_dir.display());
            ExitCode::SUCCESS
        }
        Err(err) => {
            eprintln!("wiregen: {err:#}");
            ExitCode::FAILURE
        }
    }
}
