//! wiregen — generates the web client's TypeScript wire types
//! (`web/packages/proto/src/generated/`) from the Rust wire crates
//! (`roboco-proto`, `roboco-doc`, `roboco-engine`, `roboco-update`) via ts-rs.
//!
//! - `cargo run -p wiregen` — regenerate in place.
//! - `cargo run -p wiregen -- --check` — regenerate into a temp dir and fail on
//!   any diff against the checked-in output (the CI freshness gate: a Rust wire
//!   change without regeneration is a red build).
//!
//! Serde naming carries over exactly (camelCase fields, kebab-case/lowercase
//! fieldless enums, internally tagged enums, the untagged `TranscriptFrame`) —
//! the derives only ADD `ts_rs::TS`; they must never change serde output (the
//! existing serde contract tests in the wire crates pin that). The few
//! untyped/dynamic fields (`modelOptions`, `ToolCall::Mcp/Unknown.input`,
//! ad-hoc `json!` replies) are hand-written in `web/packages/proto/src/shims.ts`.

use std::{
    collections::BTreeMap,
    fs,
    path::{Path, PathBuf},
    process::ExitCode,
};

use anyhow::{Context, Result};
use ts_rs::{Config, TS};

/// Header stamped on every generated file.
