import os
import subprocess
import sys
import unittest
from unittest import mock

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import lockfile  # noqa: E402

REG = "registry+https://github.com/rust-lang/crates.io-index"


def lock(*pkgs):
    out = ["# This file is automatically @generated by Cargo.", "version = 4", ""]
    for p in pkgs:
        name, version = p[0], p[1]
        source = p[2] if len(p) > 2 else REG
        out += ["[[package]]", f'name = "{name}"', f'version = "{version}"']
        if source:
            out.append(f'source = "{source}"')
        out += ['dependencies = [', ' "serde",', ']', ""]
    return "\n".join(out).encode("utf-8")


ZUI = "git+https://github.com/zeronsh/zui?rev=aaa#aaa"
ZUI2 = "git+https://github.com/zeronsh/zui?rev=bbb#bbb"


class LockfileTest(unittest.TestCase):
    def test_packages(self):
        pk = lockfile.packages(lock(("serde", "1.0.1"), ("roboco-ui", "0.2.1", "")).replace(b"\n", b"\r\n"))
        self.assertEqual(pk, {("serde", "1.0.1"): REG, ("roboco-ui", "0.2.1"): ""})
        self.assertEqual(lockfile.packages(None), {})

    def test_plan(self):
        base = lock(("serde", "1.0.1"), ("tokio", "1.40.0"), ("nucleo", "0.5.0"), ("gpui", "0.2.0", ZUI),
                    ("roboco-ui", "0.2.127", ""), ("rand", "0.8.5"))
        theirs = lock(("serde", "1.0.2"), ("tokio", "1.41.0"), ("fff-search", "0.3.0"), ("gpui", "0.2.0", ZUI2),
                      ("roboco-ui", "0.2.128", ""), ("rand", "0.9.0"))
        ours = lock(("serde", "1.0.1"), ("tokio", "1.41.0"), ("nucleo", "0.5.0"), ("gpui", "0.2.0", ZUI),
                    ("roboco-ui", "0.3.0", ""), ("rand", "0.8.4"))
        p = lockfile.plan(ours, base, theirs)
        self.assertEqual(p["updates"], [("serde", "1.0.1", "1.0.2")])
        self.assertEqual(p["already"], ["tokio"])
        self.assertEqual(p["added"], ["fff-search", "rand"])  # rand: Roboco isn't on upstream's old version
        self.assertEqual(p["removed"], ["nucleo"])
        self.assertEqual(p["git"], ["gpui"])
        self.assertNotIn("roboco-ui", sum((v if isinstance(v, list) else [] for v in p.values()), []))
        cmds = lockfile.commands(p)
        self.assertEqual(cmds[0], ["cargo", "metadata", "--format-version", "1"])
        self.assertEqual(cmds[1], ["cargo", "update", "-p", "serde@1.0.1", "--precise", "1.0.2"])
        text = " ".join(lockfile.describe(p))
        self.assertIn("serde 1.0.1 -> 1.0.2", text)
        self.assertIn("Roboco pins its own forks", text)

    def test_is_lockfile(self):
        self.assertTrue(lockfile.is_lockfile("Cargo.lock"))
        self.assertTrue(lockfile.is_lockfile("apps/x/Cargo.lock"))
        self.assertFalse(lockfile.is_lockfile("Cargo.toml"))

    def test_refresh_reports_failures(self):
        p = {"updates": [("serde", "1.0.1", "1.0.2"), ("rand", "0.8.5", "0.9.0")],
             "added": [], "removed": [], "git": [], "already": []}
        calls = []

        def fake_run(cmd, cwd, capture_output, timeout):
            calls.append((cmd, cwd))
            if "serde@1.0.1" in cmd:
                return subprocess.CompletedProcess(cmd, 101, b"", b"warning\nerror: no matching package\n")
            if "rand@0.8.5" in cmd:
                raise FileNotFoundError("cargo")
            return subprocess.CompletedProcess(cmd, 0, b"{}", b"")

        with mock.patch.object(lockfile.subprocess, "run", fake_run):
            ran = lockfile.refresh("/wt", p)
        self.assertEqual([c[1] for c in calls], ["/wt"] * 3)
        self.assertEqual(ran[0], ("cargo metadata --format-version 1", True, ""))
        self.assertEqual(ran[1], ("cargo update -p serde@1.0.1 --precise 1.0.2", False,
                                  "error: no matching package"))
        self.assertFalse(ran[2][1])


if __name__ == "__main__":
    unittest.main()
